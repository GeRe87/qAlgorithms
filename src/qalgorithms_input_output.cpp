    // NOLINTBEGIN(concurrency-mt-unsafe)
    UserInputSettings passCliArgs(const int argc, const char *argv[])
    {
        UserInputSettings args;
        assert(args.inputPaths.empty());
        assert(args.outputPath.empty());

        for (int i = 1; i < argc; i++)
        {
            std::string argument = argv[i];
            if ((argument == "-h") || (argument == "--help"))
            {
                printf("%s%s", VERSION, helpinfo);
                exit(0);
            }

            if ((argument == "-v") || (argument == "--version"))
            {
                printf("%s", VERSION);
                exit(0);
            }

            if ((argument == "-s") || (argument == "--silent"))
            {
                args.silent = true;
            }
            else if ((argument == "-v") || (argument == "--verbose"))
            {
                args.verboseProgress = true;
            }
            else if ((argument == "-i") || (argument == "--input"))
            {
                ++i;
                if (i == argc)
                {
                    (void)fprintf(stderr, "Error: argument -input was set, but no valid file supplied.\n");
                    exit(1);
                }
                std::string inputString = argv[i];
                if (inputString.empty() || inputString[0] == '-')
                {
                    (void)fprintf(stderr, "Error: argument -input was set, but no valid file supplied.\n");
                    exit(1);
                }
                for (; i < argc; i++)
                {
                    inputString = argv[i];
                    if (inputString.empty() || inputString[0] == '-')
                    {
                        break;
                    }
                    args.inputPaths.push_back(inputString);
                }
                --i;
            }
            else if ((argument == "-tl") || (argument == "--tasklist"))
            {
                (void)fprintf(stderr, "Error: tasklist support is not integrated at the moment.\n");

                args.tasklistSpecified = true;
                ++i;
                const char format_err_tl[] = "Error: argument -tasklist was set, but no valid file supplied.\n";
                if (i == argc)
                {
                    (void)fprintf(stderr, format_err_tl);
                    exit(1);
                }
                std::string inputString = argv[i];
                if (inputString.empty() || inputString[0] == '-')
                {
                    (void)fprintf(stderr, format_err_tl);
                    exit(1);
                }
                /*@todo
                the task file should contain a list of all files the program
                should run over. It should give access to additional settings,
                for example per-group output location and multiple recursion points.
                Lines can be commented out with a "#". empty lines are ignored.
                The file must start with a line containing only "TASKFILE" and
                should accept some standardised user data like name and project.
                Suggested options:
                    ADDDATE: The current date (YYYYMMDD) is added with an underscore
                    to the front of the filename
                */
                args.inputPaths.push_back(inputString);
            }

            else if ((argument == "-o") || (argument == "--output"))
            {
                if (!args.outputPath.empty())
                {
                    (void)fprintf(stderr, "Error: two output locations specified. For complex "
                                          "output location structures, it is recommended you use the tasklist"
                                          " input (not implemented yet).\n");
                    args.outputPath = "";
                    exit(1);
                }

                ++i;
                if (i == argc)
                {
                    (void)fprintf(stderr, "Error: no output directory specified.\n");
                    exit(1);
                }
                args.outputPath = argv[i];
                if (args.outputPath.empty() || args.outputPath[0] == '-')
                    throw std::invalid_argument("-o / --output requires a directory path.");
            }
            else if ((argument == "-pc") || (argument == "--printcentroids") || (argument == "-printcentroids"))
            {
                args.printCentroids = true;
            }
            else if (argument == "--centroid-mzml")
            {
                args.printCentroidsMZML = true;
            }
            else if ((argument == "-pb") || (argument == "--printbins") || (argument == "-printbins"))
            {
                args.printBins = true;
            }
            else if ((argument == "-pf") || (argument == "--printfeatures") || (argument == "-printfeatures"))
            {
                args.printFeatures = true;
            }
            else if (argument == "--fifo-feature-mz")
            {
                args.fifoFeatureMz = true;
            }
            else if (argument == "--peak-folding")
            {
                args.peakFolding = true;
            }
            else if (argument == "--superspectrum")
            {
                if (args.superspectrum)
                    throw std::invalid_argument("Select superspectrum mode only once");
                args.superspectrum = true;
            }
            else if (argument == "--superspectrum-fixed")
            {
                if (argc - i <= 3 || args.superspectrum)
                    throw std::invalid_argument("--superspectrum-fixed requires GRID_STEP MAX_GAP MAX_HALF_WIDTH");
                auto positive = [&](const char *field)
                {
                    const std::string value = argv[++i];
                    size_t end = 0;
                    const double parsed = std::stod(value, &end);
                    if (end != value.size() || !(parsed > 0 && std::isfinite(parsed)))
                        throw std::invalid_argument(std::string("Invalid superspectrum ") + field);
                    return parsed;
                };
                const double step = positive("grid step");
                const double gap = positive("maximum gap");
                const double width = positive("maximum half-width");
                if (width < 2 || width > maxscale_global || std::floor(width) != width)
                    throw std::invalid_argument("Superspectrum maximum half-width must be an integer in the compiled scale range");
                args.superspectrum = true;
                args.fixedSuperspectrum = SuperspectrumSettings{step, gap, static_cast<size_t>(width)};
            }
            else if (argument == "--calibrated-peaks")
            {
                if (argc - i <= 8 || args.calibratedPeaks)
                    throw std::invalid_argument("--calibrated-peaks requires one model and seven numeric arguments");
                auto number = [&](const char *field)
                {
                    const std::string value = argv[++i];
                    size_t end = 0;
                    const double parsed = std::stod(value, &end);
                    if (end != value.size() || !std::isfinite(parsed))
                        throw std::invalid_argument(std::string("Invalid calibrated peak ") + field);
                    return parsed;
                };
                auto count = [&](const char *field)
                {
                    const std::string value = argv[++i];
                    size_t end = 0;
                    if (value.empty() || value.find_first_not_of("0123456789") != std::string::npos)
                        throw std::invalid_argument(std::string("Invalid calibrated peak ") + field);
                    const auto parsed = std::stoull(value, &end);
                    if (end != value.size() || parsed > std::numeric_limits<size_t>::max())
                        throw std::invalid_argument(std::string("Invalid calibrated peak ") + field);
                    return static_cast<size_t>(parsed);
                };
                CalibratedPeakSettings settings;
                settings.model = argv[++i];
                settings.step = number("step");
                settings.minimumAreaMz = number("minimum area");
                settings.minimumCoverage = number("minimum coverage");
                settings.minScale = count("minimum scale");
                settings.maxScale = count("maximum scale");
                settings.alpha = number("alpha");
                settings.rotations = count("rotations");
                const bool module = settings.model.rfind("module:", 0) == 0 && settings.model.size() > 7;
                if ((settings.model != "quadratic" && settings.model != "hyperbolic" && !module)
                    || !(settings.step > 0 && settings.minimumAreaMz > 0)
                    || (settings.model == "quadratic" && (settings.step != 1 || settings.maxScale > maxscale_global))
                    || !(settings.minimumCoverage > 0 && settings.minimumCoverage < 1)
                    || settings.minScale < 2 || settings.maxScale < settings.minScale
                    || !(settings.alpha > 0 && settings.alpha < 1) || settings.rotations == 0)
                    throw std::invalid_argument("Invalid --calibrated-peaks model, thresholds or window settings");
                args.calibratedPeaks = std::move(settings);
            }
            else if (argument == "--folding-axis")
            {
                args.foldingOptionSpecified = true;
                if (++i == argc)
                    throw std::invalid_argument("--folding-axis requires tof or orbitrap");
                const std::string value = argv[i];
                if (value == "tof") args.foldingAxis = FoldingCliAxis::tof;
                else if (value == "orbitrap") args.foldingAxis = FoldingCliAxis::orbitrap;
                else throw std::invalid_argument("--folding-axis must be tof or orbitrap");
            }
            else if (argument == "--folding-model")
            {
                args.foldingOptionSpecified = true;
                if (++i == argc)
                    throw std::invalid_argument("--folding-model requires symmetric or asymmetric");
                const std::string value = argv[i];
                if (value == "symmetric") args.foldingSymmetric = true;
                else if (value == "asymmetric") args.foldingSymmetric = false;
                else throw std::invalid_argument("--folding-model must be symmetric or asymmetric");
            }
            else if (argument == "--folding-min-intensity")
            {
                args.foldingOptionSpecified = true;
                if (++i == argc)
                    throw std::invalid_argument("--folding-min-intensity requires a positive number");
                size_t parsed = 0;
                const std::string value = argv[i];
                args.foldingMinIntensity = std::stod(value, &parsed);
                if (parsed != value.size() || !std::isfinite(args.foldingMinIntensity) ||
                    !(args.foldingMinIntensity > 0.0))
                    throw std::invalid_argument("--folding-min-intensity requires a finite positive number");
            }
            else if (argument == "--folding-max-scans")
            {
                args.foldingOptionSpecified = true;
                if (++i == argc)
                    throw std::invalid_argument("--folding-max-scans requires a positive integer");
                size_t parsed = 0;
                const std::string value = argv[i];
                if (value.empty() || value[0] == '-')
                    throw std::invalid_argument("--folding-max-scans requires a positive integer");
                const unsigned long long count = std::stoull(value, &parsed);
                if (parsed != value.size() || count == 0 ||
                    count > std::numeric_limits<size_t>::max())
                    throw std::invalid_argument("--folding-max-scans requires a positive integer");
                args.foldingMaxScans = static_cast<size_t>(count);
            }
            else if ((argument == "-sp") || (argument == "--subprofile"))
            {
                args.printSubProfile = true;
            }
            else if ((argument == "-ppf") || (argument == "--printcomponentsF"))
            {
                args.printComponentRegs = true;
                args.printFeatures = true;
            }
            else if ((argument == "-ppb") || (argument == "--printcomponentsB"))
            {
                args.printComponentRegs = true;
                args.printComponentBins = true;
            }
            else if ((argument == "-px") || (argument == "--printfeatcen"))
            {
                args.printFeatCens = true;
            }
            else if ((argument == "-pa") || (argument == "--printall") || (argument == "-printall"))
            {
                args.printCentroids = true;
                args.printBins = true;
                args.printFeatures = true;
                args.printSubProfile = true;
                args.printFeatCens = true;
                args.printComponentRegs = true;
                args.printComponentBins = true;
            }
            else if ((argument == "-prfsc") || (argument == "--profile-section"))
            {
                args.printProfileSection = true;
                // we expect exactly four floats to be supplied next. The order is always mz -> rt and lower -> upper
                // @todo error handling for bad input
                if (i + 4 >= argc)
                    throw std::invalid_argument("--profile-section requires four numeric bounds.");
                args.prof_lim_mz_lower = std::stof(argv[i + 1]);
                args.prof_lim_mz_upper = std::stof(argv[i + 2]);
                args.prof_lim_rt_lower = std::stof(argv[i + 3]);
                args.prof_lim_rt_upper = std::stof(argv[i + 4]);
                i += 4;
            }
            else if (argument == "--time-min")
            {
                args.time_seconds = false;
            }
            else if (argument == "--time-sec")
            {
                args.time_seconds = true;
            }
            else if (argument == "--log") // @todo if logging is off by default, nobody who would benefit from it will turn it on
            {
                args.doLogging = true;
            }
            else if (argument == "--skip-error")
            {
                (void)fprintf(stderr, "Warning: processing will ignore defective files.\n");
                args.skipError = true;
            }
            else if (argument == "--skip-existing")
            {
                args.noOverwrite = true;
            }
            else if (argument == "--skip-ahead")
            {
                ++i;
                if (i == argc)
                {
                    (void)fprintf(stderr, "Error: no value to skip ahead specified.\n");
                    exit(1);
                }

                const char *str = argv[i];
                char *endptr = nullptr;
                int64_t skip = strtol(str, &endptr, 10);
                if (endptr == str || *endptr != '\0')
                {
                    (void)fprintf(stderr, "Error: you cannot skip ahead by \"%s\" entries.\n", argv[i]);
                    exit(1);
                }
                if (skip < 0)
                {
                    (void)fprintf(stderr, "Error: you cannot skip ahead a negative number of entries.\n");
                    exit(1);
                }

                args.skipAhead = (size_t)skip;
            }
            else
            {
                (void)fprintf(stderr, "Error: unknown argument \"%s\".\n", argument.c_str());
                exit(1);
            }
        } // end of reading in command line arguments

        // adjust time to seconds if necessary
        if (!args.time_seconds)
        {
            args.prof_lim_rt_lower *= 60;
            args.prof_lim_rt_upper *= 60;
        }
        return args;
    }
    // NOLINTEND(concurrency-mt-unsafe)

    bool inputsAreSensible(UserInputSettings &args)
    {
        // program exits if an error is found, but only after displaying all warnings
        bool goodInputs = true;

        if (args.inputPaths.empty())
        {
            (void)fprintf(stderr, "Error: no input file supplied. Specify a file or directory using the -i or "
                                  "-tl flag. Execute qAlgorithms with the -h flag for more information.\n");
            goodInputs = false;
        }
        if (!args.outputPath.empty() && !args.printCentroids && !args.printBins &&
            !args.printFeatures && !args.printProfileSection && !args.printCentroidsMZML &&
            !args.printComponentRegs && !args.printComponentBins && !args.printFeatCens && !args.printSubProfile &&
            !args.peakFolding && !args.calibratedPeaks && !args.superspectrum)
            args.printFeatures = true;
        if (args.outputPath.empty())
        {
            if (args.printCentroids ||
                args.printFeatures ||
                args.printBins ||
                args.printProfileSection)
            {
                std::string badOptions;
                int prevBad = 0;
                if (args.printProfileSection)
                {
                    // if (prevBad > 0) // uncomment if an earlier return point is introduced
                    // {
                    //     badOptions += ", ";
                    // }
                    prevBad += 1;
                    badOptions += "-profile-section";
                }
                if (args.printCentroids)
                {
                    if (prevBad > 0)
                    {
                        badOptions += ", ";
                    }
                    prevBad += 1;
                    badOptions += "-printcentroids";
                }
                if (args.printCentroidsMZML)
                {
                    if (prevBad > 0)
                    {
                        badOptions += ", ";
                    }
                    prevBad += 1;
                    badOptions += "-centroid-mzml";
                }
                if (args.printBins)
                {
                    if (prevBad > 0)
                    {
                        badOptions += ", ";
                    }
                    prevBad += 1;
                    badOptions += "-printbins";
                }
                if (args.printFeatures)
                {
                    if (prevBad > 0)
                    {
                        badOptions += ", ";
                    }
                    prevBad += 1;
                    badOptions += "-printfeatures";
                }

                if (prevBad > 1)
                {
                    (void)fprintf(stderr, "Error: output flags \"%s\" were set, but no output path supplied.\n",
                                  badOptions.c_str());
                }
                else
                {
                    (void)fprintf(stderr, "Error: output flag \"%s\" was set, but no output path supplied.\n",
                                  badOptions.c_str());
                }
                goodInputs = false;
            }
            else
            {
                (void)fprintf(stderr, "Warning: no output directory specified. No output files will be written.\n");
            }
        }
        else if (!std::filesystem::exists(args.outputPath))
        {
            std::filesystem::create_directories(args.outputPath);
        }
        else if (std::filesystem::status(args.outputPath).type() != std::filesystem::file_type::directory)
        {
            (void)fprintf(stderr, "Error: the output location must be a directory.\n");
            goodInputs = false;
        }
        if (args.peakFolding)
        {
            if (args.outputPath.empty())
            {
                (void)fprintf(stderr, "Error: --peak-folding requires an output directory (-o).\n");
                goodInputs = false;
            }
            if (args.foldingAxis == FoldingCliAxis::unspecified)
            {
                (void)fprintf(stderr, "Error: --peak-folding requires --folding-axis tof or orbitrap.\n");
                goodInputs = false;
            }
            if (args.printCentroids || args.printCentroidsMZML || args.printBins ||
                args.printFeatures || args.printProfileSection || args.printSubProfile ||
                args.printFeatCens || args.printComponentRegs || args.printComponentBins)
            {
                (void)fprintf(stderr, "Error: --peak-folding cannot be combined with standard qPeaks output options.\n");
                goodInputs = false;
            }
        }
        else if (args.foldingOptionSpecified)
        {
            (void)fprintf(stderr, "Error: folding-specific options require --peak-folding.\n");
            goodInputs = false;
        }
        if (args.calibratedPeaks && (args.outputPath.empty() || args.peakFolding || args.printCentroids
            || args.printCentroidsMZML || args.printBins || args.printFeatures || args.printProfileSection
            || args.printSubProfile || args.printFeatCens || args.printComponentRegs || args.printComponentBins))
        {
            (void)fprintf(stderr, "Error: --calibrated-peaks requires -o and its own scan-level output.\n");
            goodInputs = false;
        }
        if (args.fifoFeatureMz && (!args.printFeatures || args.outputPath.empty() ||
            args.peakFolding || args.calibratedPeaks || args.printCentroidsMZML ||
            args.printComponentRegs || args.printComponentBins))
        {
            (void)fprintf(stderr, "Error: --fifo-feature-mz requires standard feature CSV output (-o, optionally --printfeatures).\n");
            goodInputs = false;
        }
        if (args.superspectrum && (args.outputPath.empty() || args.peakFolding || args.calibratedPeaks
            || args.fifoFeatureMz || args.printCentroids || args.printCentroidsMZML || args.printBins
            || args.printFeatures || args.printProfileSection || args.printSubProfile
            || args.printFeatCens || args.printComponentRegs || args.printComponentBins))
        {
            (void)fprintf(stderr, "Error: --superspectrum requires -o and writes its own feature and centroid outputs.\n");
            goodInputs = false;
        }

        if (args.silent && args.verboseProgress)
        {
            (void)fprintf(stderr, "Warning: -verbose overrides -silent.\n");
            args.silent = false;
        }

        // set termination point here so that the program will only process data when necessary
        // note: since this statement is only evaluated once, it must be set up in the same order
        // as the termination points in the main function. Since these cannot be arbitrary, that
        // is not considered an issue for now.
        if (args.printComponentRegs || args.printComponentBins)
        {
            args.term = TerminateAfter::components;
        }
        else if (args.printFeatures || args.printFeatCens || args.printSubProfile)
        {
            args.term = TerminateAfter::features;
        }
        else if (args.printBins)
        {
            args.term = TerminateAfter::binning;
        }
        else if (args.printCentroids)
        {
            args.term = TerminateAfter::centroids;
        }
        else if (args.printProfileSection)
        {
            args.term = TerminateAfter::profilesec;
        }
        else
        {
            args.term = TerminateAfter::never;
        }

        if (args.printCentroidsMZML && (args.term != TerminateAfter::never))
        {
            (void)fprintf(stderr, "Error: Either output a centroided mzML or perform feature construction.\n");
            goodInputs = false;
        }
        if (args.printCentroidsMZML && !args.outputPath.empty())
        {
            (void)fprintf(stderr, "Error: Centroiding does not support a custom output directory yet.\n");
            goodInputs = false;
        }

        if (args.term == TerminateAfter::never && !args.outputPath.empty() && !args.peakFolding &&
            !args.calibratedPeaks && !args.superspectrum)
        {
            (void)fprintf(stderr, "Warning: no output files will be written.\n");
        }

        return goodInputs;
    }

