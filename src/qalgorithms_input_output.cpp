    // NOLINTBEGIN(concurrency-mt-unsafe)
    std::vector<std::filesystem::path> controlInput(const UserInputSettings *args)
    {
        namespace fs = std::filesystem;
        std::vector<fs::path> tasks;
        std::set<fs::path> seen;
        auto addFile = [&](const fs::path &candidate)
        {
            if (!fs::is_regular_file(candidate))
                return;
            std::string extension = candidate.extension().string();
            std::transform(extension.begin(), extension.end(), extension.begin(),
                           [](unsigned char c) { return (char)std::tolower(c); });
            if (extension != ".mzml")
                return;
            const fs::path path = fs::canonical(candidate);
            if (seen.insert(path).second)
                tasks.push_back(path);
        };
        for (const auto &input : args->inputPaths)
        {
            const fs::path path(input);
            if (!fs::exists(path))
                throw std::runtime_error("Input path does not exist: " + input);
            if (fs::is_directory(path))
            {
                for (const auto &entry : fs::recursive_directory_iterator(path))
                    addFile(entry.path());
            }
            else
                addFile(path);
        }
        std::sort(tasks.begin(), tasks.end(), [](const fs::path &left, const fs::path &right)
                  {
                      const auto leftSize = fs::file_size(left);
                      const auto rightSize = fs::file_size(right);
                      return leftSize == rightSize ? left < right : leftSize < rightSize;
                  });
        if (tasks.empty())
            throw std::runtime_error("No mzML files were selected.");
        if (args->skipAhead >= tasks.size())
            throw std::runtime_error("--skip-ahead leaves no files to process.");
        tasks.erase(tasks.begin(), tasks.begin() + (std::ptrdiff_t)args->skipAhead);
        return tasks;
    }
